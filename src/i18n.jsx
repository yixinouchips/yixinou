export function I18nProvider({ children }) {
  // On a locale path the URL is authoritative, so a shared or indexed /de/ link always opens
  // in German. The stored preference is only the fallback for the unprefixed English tree.
  // The selector changes the URL, which is what then drives `lang`.
  const pathname = useLocation().pathname;
  const urlLocale = localeOfPath(pathname);

  const [stored, setStored] = useState(() => {
    try {
      return localStorage.getItem(LANG_KEY) || '';
    } catch {
      return '';
    }
  });

  // The URL is the ONLY authority. Falling back to the stored preference would let a
  // previous German visit render German on the unprefixed English URLs, which is both wrong
  // for the visitor and unindexable: an English URL serving German with no alternate
  // declared. English lives at the root, German under /de/, and nothing else.
  const lang = urlLocale && urlLocale in UI ? urlLocale : 'en';

  useEffect(() => {
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch {
      /* storage unavailable */
    }
    const loc = LOCALES.find((l) => l.code === lang);
    document.documentElement.lang = loc?.hreflang || 'en';
    document.documentElement.dir = loc?.dir === 'rtl' ? 'rtl' : 'ltr';
  }, [lang]);

  // Kept so the selector can record a preference for a future first-visit redirect. It does
  // not change the language on its own: the selector navigates to the locale prefix, and the
  // prefix is what selects the dictionary.
  const setLang = (code) => setStored(code in UI ? code : 'en');
  const dict = UI[lang] || UI.en;
  const t = (key) => dict[key] ?? UI.en[key] ?? key;

  return <I18nContext.Provider value={{ lang, t, setLang }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
